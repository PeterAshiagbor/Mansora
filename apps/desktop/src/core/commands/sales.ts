import { z } from 'zod';
import { fail, mulDivRound, PAYMENT_METHODS, priceCart, refundLineAmount, SETTLEMENT_METHODS, settlePayments, splitRefund, sum } from '@mansora/domain';
import { dayBounds, defineCommands, zApprover, zId, zMoney, zOptText, zQty, zRange, zText, type Ctx } from '../engine';
import { renderReceiptHtml } from '../receipt';
import { moveStock, nextNumber, openShift, requireOpenShift } from '../stock';

function loadSale(ctx: Ctx, id: string) {
  const sale = ctx.get(
    `SELECT s.*, u.name AS cashier_name, c.name AS customer_name, c.phone AS customer_phone
     FROM sales s JOIN users u ON u.id = s.cashier_id LEFT JOIN customers c ON c.id = s.customer_id WHERE s.id = ?`,
    id,
  );
  if (!sale) fail('NOT_FOUND', 'Sale not found');
  // Cashiers may only open their own sales.
  if (!ctx.can('sale.view_all') && sale.cashier_id !== ctx.user.id) fail('PERMISSION_DENIED', 'You can only view your own sales', { permission: 'sale.view_all' });
  const items = ctx.all(
    `SELECT i.*, COALESCE((SELECT SUM(r.quantity) FROM refund_items r WHERE r.sale_item_id = i.id), 0) AS refunded_quantity,
            COALESCE((SELECT SUM(r.amount) FROM refund_items r WHERE r.sale_item_id = i.id), 0) AS refunded_amount
     FROM sale_items i WHERE i.sale_id = ? ORDER BY i.rowid`,
    id,
  );
  const payments = ctx.all('SELECT * FROM payments WHERE sale_id = ? ORDER BY rowid', id);
  const refunds = ctx.all(
    `SELECT r.*, a.name AS authorised_by_name, q.name AS requested_by_name FROM refunds r
     JOIN users a ON a.id = r.authorised_by JOIN users q ON q.id = r.requested_by WHERE r.sale_id = ? ORDER BY r.created_at`,
    id,
  );
  const credit = ctx.get('SELECT * FROM credit_accounts WHERE sale_id = ?', id) ?? null;
  if (!ctx.can('product.cost')) {
    delete sale.cost_total;
    for (const i of items) delete i.cost_snapshot;
    for (const r of refunds) delete r.cost_total;
  }
  return { sale, items, payments, refunds, credit };
}

export const salesCommands = defineCommands({
  /**
   * Complete a sale. Everything - the sale, its lines, payments, stock
   * movements, balances, any credit account, the audit entry and the sync
   * event - commits in ONE local transaction or not at all.
   */
  'sale.complete': {
    perm: 'sale.create',
    mutates: true,
    input: z.object({
      /** Generated by the checkout screen once per basket: retrying the same basket can never create a second sale. */
      id: zId,
      lines: z.array(z.object({ productId: zId, quantity: zQty, discount: zMoney.default(0) })).min(1).max(500),
      cartDiscount: zMoney.default(0),
      tenders: z.array(z.object({ method: z.enum(PAYMENT_METHODS), amount: zMoney, reference: zOptText(80) })).max(10),
      customerId: zId.nullish(),
      dueDate: z.string().regex(/^\d{4}-\d{2}-\d{2}$/).nullish(),
      approver: zApprover,
    }),
    run: (ctx, input) => {
      const existing = ctx.get('SELECT id, receipt_no FROM sales WHERE id = ?', input.id);
      if (existing) return { id: existing.id, receiptNo: existing.receipt_no, duplicate: true };

      const shift = requireOpenShift(ctx, 'making a sale');
      if (new Set(input.lines.map((l) => l.productId)).size !== input.lines.length) fail('INVALID_INPUT', 'Each product may appear only once in the basket');
      const products = input.lines.map((l) => {
        const p = ctx.get(
          'SELECT p.*, COALESCE(b.average_cost, p.cost_price) AS average_cost FROM products p LEFT JOIN stock_balances b ON b.product_id = p.id WHERE p.id = ?',
          l.productId,
        );
        if (!p || !p.active) fail('PRODUCT_UNAVAILABLE', 'A product in the basket is no longer available', { productId: l.productId });
        return p;
      });
      // Prices always come from the local catalogue, never from the screen.
      const cart = priceCart(input.lines.map((l, i) => ({ productId: l.productId, quantity: l.quantity, unitPrice: products[i].selling_price, discount: l.discount })), input.cartDiscount);
      let discountApprovedBy: string | null = null;
      if (cart.discountTotal > 0) {
        // Optional owner-set ceiling (percent of the basket before discount). Above it, only the owner may approve.
        const maxBps = Number(ctx.setting('max_discount_bps') ?? 0);
        if (maxBps > 0 && mulDivRound(cart.discountTotal, 10_000, cart.subtotal) > maxBps) {
          const approverId = input.approver ? ctx.engine.verifyCredentials(input.approver.username, input.approver.password).id : ctx.user.id;
          if (ctx.engine.loadUser(approverId)?.role !== 'owner') fail('OWNER_APPROVAL_REQUIRED', `Discounts above ${maxBps / 100}% need the owner's approval`, { maxBps });
          discountApprovedBy = approverId;
        } else discountApprovedBy = ctx.authorise('sale.discount', input.approver);
      }
      const settlement = settlePayments(cart.total, input.tenders);
      if (settlement.creditAmount > 0) {
        if (!input.customerId) fail('CUSTOMER_REQUIRED', 'Choose a customer for a credit sale');
        ctx.authorise('credit.sell', input.approver);
      }
      if (input.customerId && !ctx.get('SELECT 1 FROM customers WHERE id = ? AND active = 1', input.customerId)) fail('NOT_FOUND', 'Customer not found');

      const now = ctx.now();
      const receiptNo = nextNumber(ctx, 'R');
      const costs = products.map((p) => p.average_cost as number);
      ctx.insert('sales', {
        id: input.id, receipt_no: receiptNo, shift_id: shift.id, cashier_id: ctx.user.id, customer_id: input.customerId ?? null,
        subtotal: cart.subtotal, discount_total: cart.discountTotal, total: cart.total, cash_tendered: settlement.cashTendered,
        change_given: settlement.change, cost_total: sum(cart.lines.map((l, i) => l.quantity * costs[i])), status: 'completed',
        discount_approved_by: discountApprovedBy, created_at: now,
      });
      cart.lines.forEach((l, i) => {
        ctx.insert('sale_items', {
          id: ctx.id(), sale_id: input.id, product_id: l.productId, product_name: products[i].name, sku: products[i].sku, quantity: l.quantity,
          unit_price: l.unitPrice, cost_snapshot: costs[i], discount: l.discount, line_total: l.lineTotal,
        });
        moveStock(ctx, { productId: l.productId, type: 'SALE', delta: -l.quantity, refType: 'sale', refId: input.id });
      });
      for (const p of settlement.payments) ctx.insert('payments', { id: ctx.id(), sale_id: input.id, method: p.method, amount: p.amount, reference: p.reference });
      if (settlement.creditAmount > 0) {
        ctx.insert('credit_accounts', {
          id: ctx.id(), customer_id: input.customerId, sale_id: input.id, original_balance: settlement.creditAmount,
          outstanding_balance: settlement.creditAmount, due_date: input.dueDate ?? null, status: 'open', created_at: now, updated_at: now,
        });
      }
      ctx.audit('sale', input.id, { receiptNo, total: cart.total, discount: cart.discountTotal, credit: settlement.creditAmount, discountApprovedBy });
      return { id: input.id, receiptNo, total: cart.total, change: settlement.change };
    },
  },

  'sale.list': {
    perm: 'sale.create',
    input: zRange.extend({ search: z.string().max(60).optional(), limit: z.number().int().min(1).max(2000).default(300) }),
    run: (ctx, input) => {
      const [from, to] = dayBounds(input);
      const where = ['s.created_at >= ?', 's.created_at < ?'];
      const params: unknown[] = [from, to];
      if (!ctx.can('sale.view_all')) (where.push('s.cashier_id = ?'), params.push(ctx.user.id));
      if (input.search?.trim()) (where.push('(s.receipt_no LIKE ? OR c.name LIKE ?)'), params.push(`%${input.search.trim()}%`, `%${input.search.trim()}%`));
      return ctx.all(
        `SELECT s.id, s.receipt_no, s.created_at, s.total, s.discount_total, u.name AS cashier_name, c.name AS customer_name,
           (SELECT GROUP_CONCAT(DISTINCT method) FROM payments p WHERE p.sale_id = s.id) AS methods,
           COALESCE((SELECT SUM(amount) FROM refunds r WHERE r.sale_id = s.id), 0) AS refunded
         FROM sales s JOIN users u ON u.id = s.cashier_id LEFT JOIN customers c ON c.id = s.customer_id
         WHERE ${where.join(' AND ')} ORDER BY s.created_at DESC, s.rowid DESC LIMIT ?`,
        ...params, input.limit,
      );
    },
  },
  'sale.get': { perm: 'sale.create', input: z.object({ id: zId }), run: (ctx, input) => loadSale(ctx, input.id) },
  'sale.receipt': {
    perm: 'sale.create',
    input: z.object({ id: zId, reprint: z.boolean().default(false) }),
    run: (ctx, input) => {
      const s = loadSale(ctx, input.id);
      const m = (k: string) => ctx.setting(k) ?? '';
      const html = renderReceiptHtml({
        business: { name: m('business_name'), phone: m('business_phone'), address: m('business_address'), footer: m('receipt_footer') },
        sale: s.sale, items: s.items, payments: s.payments, refunds: s.refunds, reprint: input.reprint,
      });
      return { html, receiptNo: s.sale.receipt_no as string };
    },
  },

  /**
   * Refund all or part of a sale. Never edits the sale: a separate refund
   * record references it. Needs refund approval (own permission or a
   * supervisor's credentials).
   */
  'refund.create': {
    perm: 'sale.create',
    mutates: true,
    input: z.object({
      id: zId,
      saleId: zId,
      reason: zText(300),
      payoutMethod: z.enum(SETTLEMENT_METHODS).default('cash'),
      lines: z.array(z.object({ saleItemId: zId, quantity: zQty, restock: z.boolean().default(true) })).min(1).max(500),
      approver: zApprover,
    }),
    run: (ctx, input) => {
      const dup = ctx.get('SELECT id, refund_no FROM refunds WHERE id = ?', input.id);
      if (dup) return { id: dup.id, refundNo: dup.refund_no, duplicate: true };
      const authorisedBy = ctx.authorise('refund.approve', input.approver);
      const sale = ctx.get('SELECT * FROM sales WHERE id = ?', input.saleId);
      if (!sale) fail('NOT_FOUND', 'Sale not found');
      if (new Set(input.lines.map((l) => l.saleItemId)).size !== input.lines.length) fail('INVALID_INPUT', 'Each sale line may appear only once in a refund');

      const lines = input.lines.map((l) => {
        const item = ctx.get(
          `SELECT i.*, COALESCE((SELECT SUM(r.quantity) FROM refund_items r WHERE r.sale_item_id = i.id), 0) AS refunded_quantity,
                  COALESCE((SELECT SUM(r.amount) FROM refund_items r WHERE r.sale_item_id = i.id), 0) AS refunded_amount
           FROM sale_items i WHERE i.id = ? AND i.sale_id = ?`,
          l.saleItemId, input.saleId,
        );
        if (!item) fail('NOT_FOUND', 'That item is not part of this sale');
        const amount = refundLineAmount({ quantity: item.quantity, lineTotal: item.line_total, refundedQuantity: item.refunded_quantity, refundedAmount: item.refunded_amount }, l.quantity);
        return { ...l, item, amount };
      });
      const amount = sum(lines.map((l) => l.amount));
      const credit = ctx.get('SELECT * FROM credit_accounts WHERE sale_id = ?', input.saleId);
      const { creditReduction, payout } = splitRefund(amount, credit?.outstanding_balance ?? 0);
      const cashOut = payout > 0 && input.payoutMethod === 'cash';
      const shift = cashOut ? requireOpenShift(ctx, 'paying a cash refund') : openShift(ctx);

      const now = ctx.now();
      const refundNo = nextNumber(ctx, 'RF');
      ctx.insert('refunds', {
        id: input.id, sale_id: input.saleId, refund_no: refundNo, amount,
        cost_total: sum(lines.filter((l) => l.restock).map((l) => l.quantity * l.item.cost_snapshot)),
        payout_method: payout > 0 ? input.payoutMethod : null, payout_amount: payout, credit_reduction: creditReduction, reason: input.reason,
        requested_by: ctx.user.id, authorised_by: authorisedBy, shift_id: shift?.id ?? null, created_at: now,
      });
      for (const l of lines) {
        ctx.insert('refund_items', { id: ctx.id(), refund_id: input.id, sale_item_id: l.saleItemId, product_id: l.item.product_id, quantity: l.quantity, amount: l.amount, restocked: l.restock ? 1 : 0 });
        // Returned goods go back into stock at the cost they were sold at. Unsellable returns are not restocked.
        if (l.restock) moveStock(ctx, { productId: l.item.product_id, type: 'SALE_REFUND', delta: l.quantity, unitCost: l.item.cost_snapshot, refType: 'refund', refId: input.id, reason: input.reason });
      }
      if (creditReduction > 0) {
        const outstanding = credit.outstanding_balance - creditReduction;
        ctx.update('credit_accounts', credit.id, { outstanding_balance: outstanding, status: outstanding === 0 ? 'settled' : 'open', updated_at: now });
      }
      ctx.audit('refund', input.id, { refundNo, saleId: input.saleId, receiptNo: sale.receipt_no, amount, payout, creditReduction, reason: input.reason, authorisedBy });
      return { id: input.id, refundNo, amount, payout, creditReduction };
    },
  },
});
