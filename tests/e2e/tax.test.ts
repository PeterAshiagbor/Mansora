import { createRequire } from 'node:module';
import { existsSync } from 'node:fs';
import { join } from 'node:path';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { startCloud, type Cloud } from '../cloud';
import { OWNER, tempDir } from '../helpers';
import { startDevHost } from '../../apps/desktop/dev/host';
import { navigate } from './navigation';
const pw = (() => { try { return createRequire(import.meta.url)('playwright'); } catch { return null; } })();

describe.skipIf(!pw || !existsSync(join(import.meta.dirname, '../../apps/desktop/dist/renderer/index.html')))('Ghana VAT browser flow', () => {
  let cloud: Cloud, host: Awaited<ReturnType<typeof startDevHost>>, browser: any, page: any;
  const consoleErrors: string[] = [];
  beforeAll(async () => {
    cloud = await startCloud(); const client = await cloud.createClient('VAT browser shop');
    host = await startDevHost({ dataDir: tempDir(), port: 0 });
    await host.engine.execute(null, 'activation.activate', { apiUrl: cloud.url, code: client.code, deviceName: 'Till', owner: OWNER });
    const token = (await host.engine.execute(null, 'auth.login', OWNER)).token;
    await host.engine.execute(token, 'product.save', { name: 'Standard VAT item', sellingPrice: 10000, costPrice: 5000, openingStock: 30, taxClass: 'standard' });
    await host.engine.execute(token, 'shift.open', { openingFloat: 0 });
    browser = await pw.chromium.launch(); page = await browser.newPage({ viewport: { width: 1366, height: 1000 } }); page.setDefaultTimeout(15000);
    page.on('pageerror', (e: Error) => consoleErrors.push(e.message));
    await page.goto(host.url);
    await page.getByLabel('Username', { exact: true }).fill(OWNER.username); await page.getByLabel('Password', { exact: true }).fill(OWNER.password);
    await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  });
  afterAll(async () => { await browser?.close(); if (host) { await new Promise<void>(r => host.server.close(() => r())); host.engine.db.close(); } await cloud?.close(); });
  it('edits tax settings, quotes and completes a taxed sale, reconciles it and exports the workbook', async () => {
    await navigate(page, 'Ghana VAT');
    await page.getByRole('button', { name: 'Tax settings', exact: true }).click();
    const dialog = page.getByRole('dialog', { name: 'Ghana tax settings' });
    await page.setViewportSize({ width: 390, height: 844 });
    const requirements = dialog.getByRole('status');
    await requirements.getByRole('button', { name: 'Complete Reason and supporting authority', exact: true }).waitFor();
    const reasonField = dialog.getByLabel('Reason and supporting authority', { exact: true });
    expect(await reasonField.getAttribute('data-requirement-invalid')).toBe('true');
    expect(await reasonField.getAttribute('aria-invalid')).toBe('true');
    expect(await dialog.getByLabel('VAT registration number', { exact: true }).getAttribute('data-requirement-invalid')).toBeNull();
    await requirements.getByRole('button', { name: 'Complete Reason and supporting authority', exact: true }).click();
    expect(await reasonField.evaluate((el: HTMLElement) => el === document.activeElement)).toBe(true);
    await reasonField.fill('   ');
    await requirements.getByRole('button', { name: 'Complete Reason and supporting authority', exact: true }).waitFor();
    await reasonField.fill('Initial setup review');
    await requirements.getByRole('button', { name: 'Complete Reason and supporting authority', exact: true }).waitFor({ state: 'hidden' });
    expect(await reasonField.getAttribute('data-requirement-invalid')).toBeNull();
    await page.setViewportSize({ width: 1366, height: 1000 });

    await dialog.getByLabel('VAT registered / legally effective obligation confirmed', { exact: true }).check();
    await requirements.getByRole('button', { name: 'Complete Business TIN', exact: true }).waitFor();
    await requirements.getByRole('button', { name: 'Complete Legal VAT effective date', exact: true }).waitFor();
    await dialog.getByLabel('Legal VAT effective date', { exact: true }).fill('2026-01-01');
    await dialog.getByLabel('Business TIN', { exact: true }).fill('BROWSER-TIN');
    await dialog.getByLabel('VAT registration number', { exact: true }).fill('BROWSER-VAT');
    await dialog.getByLabel('Catalogue selling prices', { exact: true }).selectOption('exclusive');
    await dialog.getByLabel('Reason and supporting authority', { exact: true }).fill('Registration and exclusive prices verified');
    await dialog.getByRole('button', { name: 'Save dated settings' }).click();
    await dialog.waitFor({ state: 'hidden' });
    await navigate(page, 'New sale');
    const product = page.getByRole('button').filter({ hasText: 'Standard VAT item' });
    expect(await product.textContent()).toContain('120.00');
    await product.click();
    await page.getByTestId('basket-total').filter({ hasText: '120.00' }).waitFor();
    await page.getByRole('button', { name: 'Pay (F9)', exact: true }).click();
    const pay = page.getByRole('dialog');
    await pay.getByLabel('Cash received', { exact: true }).fill('120');
    await pay.getByRole('button', { name: /Complete sale/ }).click();
    await page.getByRole('dialog', { name: 'Sale completed', exact: true }).waitFor();
    const row = host.engine.db.prepare('SELECT total, tax_snapshot FROM sales').get() as any;
    expect(row.total).toBe(12000); expect(JSON.parse(row.tax_snapshot)).toMatchObject({ vat: 1500, nhil: 250, getfund: 250 });
    await page.getByRole('button', { name: /New sale.*Enter/ }).click();
    await navigate(page, 'Ghana VAT');
    await page.getByRole('heading', { name: 'VAT and levy reconciliation' }).waitFor();
    const download = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Download VAT workbook', exact: true }).click();
    expect((await download).suggestedFilename()).toMatch(/^Ghana-VAT-2026-\d{2}\.xlsx$/);
    expect(consoleErrors).toEqual([]);
  });
  it('shows a persistent amendment warning and opens the shop VAT guide', async () => {
    const token = (await host.engine.execute(null, 'auth.login', OWNER)).token;
    await host.engine.execute(token, 'tax.configure', { effectiveDate: new Date().toISOString().slice(0, 10), registered: true, registrationDate: '2026-01-01', tin: 'BROWSER-TIN', supplyType: 'services', reason: 'Synthetic service profile needing review' });
    await navigate(page, 'Dashboard');
    await page.getByText(/Service VAT amendment needs confirmation/).waitFor();
    await navigate(page, 'Ghana VAT');
    await page.getByRole('button', { name: 'VAT guide', exact: true }).last().click();
    await page.getByRole('heading', { name: 'Streamlined GRA submission and E-VAT certification', exact: true }).waitFor();
    await page.getByRole('heading', { name: 'Service amendment: action required', exact: true }).waitFor();
    expect(consoleErrors).toEqual([]);
  });

  it('requires fiscal reconciliation and captures an actual submission date before recording a filing, then opens an evidenced amendment', async () => {
    const token=(await host.engine.execute(null,'auth.login',OWNER)).token;
    await host.engine.execute(token,'tax.configure',{effectiveDate:'2026-01-01',registered:true,registrationDate:'2026-01-01',tin:'BROWSER-TIN',reason:'Synthetic historical registration evidence'});
    await navigate(page,'Ghana VAT');
    await page.getByLabel('VAT month',{exact:true}).fill('2026-10');
    await page.getByRole('button',{name:'Record GRA filing',exact:true}).click();
    const filing=page.getByRole('dialog',{name:'Record GRA filing · 2026-10',exact:true});
    await filing.getByLabel('GRA acknowledgement reference',{exact:true}).fill('SYNTHETIC-ACK');
    await filing.getByLabel('Reconciliation / filing note',{exact:true}).fill('Synthetic browser test: no GRA submission');
    await filing.getByLabel('I reconciled the export, reviewed the warnings and filed these figures with GRA.',{exact:true}).check();
    expect(await filing.getByRole('button',{name:'Record filed return',exact:true}).isEnabled()).toBe(false);
    await filing.getByLabel('I reconciled the figures and tax documents to the GRA-approved fiscal records or authorised filing process.',{exact:true}).check();
    await filing.getByRole('button',{name:'Record filed return',exact:true}).click();
    await filing.waitFor({state:'hidden'});
    await page.getByRole('button',{name:'GRA-authorised amendment',exact:true}).click();
    const amendment=page.getByRole('dialog',{name:'GRA-authorised amendment · 2026-10',exact:true});
    await amendment.getByLabel('GRA approval reference',{exact:true}).fill('SYNTHETIC-APPROVAL');
    await amendment.getByLabel('Applicable legal/GRA authority',{exact:true}).fill('Synthetic fixture only');
    await amendment.getByLabel('Grounds for amendment',{exact:true}).fill('Browser workflow verification');
    await amendment.getByLabel('I hold GRA approval for this amendment.',{exact:true}).check();
    await amendment.getByRole('button',{name:'Open amendment draft',exact:true}).click();
    await amendment.waitFor({state:'hidden'});
    const rows=host.engine.db.prepare("SELECT kind,payload FROM tax_records WHERE kind IN ('filing','period_reopened')").all() as any[];
    expect(rows.map(r=>r.kind)).toEqual(['filing','period_reopened']);
    expect(JSON.parse(rows[0].payload).submittedDate).toMatch(/^2026-11-/);
    expect(consoleErrors).toEqual([]);
  });
  it('shows backdated exposure after Mansora re-enables collection without altering the original sale', async () => {
    const path=`/v1/admin/clients/${host.engine.meta('tenant_id')}/features/vat`;
    const disabled=await cloud.api('PUT',path,{enabled:false,reason:'Synthetic browser VAT suspension',expectedRevision:0});
    expect(disabled.status).toBe(200);
    const token=(await host.engine.execute(null,'auth.login',OWNER)).token;
    expect((await host.engine.execute(token,'sync.run')).ok).toBe(true);
    await navigate(page,'New sale');
    const product=page.getByRole('button').filter({hasText:'Standard VAT item'});
    expect(await product.textContent()).toContain('100.00');
    const productId=(await host.engine.execute(token,'product.list')).find((p:any)=>p.name==='Standard VAT item').id;
    const sale=await host.engine.execute(token,'sale.complete',{id:crypto.randomUUID(),lines:[{productId,quantity:1}],tenders:[{method:'cash',amount:10000}]});
    const before=host.engine.db.prepare('SELECT tax_snapshot FROM sales WHERE id=?').get(sale.id);
    await cloud.api('PUT',path,{enabled:true,reason:'Synthetic browser VAT resumption',expectedRevision:disabled.body.revision});
    expect((await host.engine.execute(token,'sync.run')).ok).toBe(true);
    await navigate(page,'Ghana VAT');
    await page.getByRole('heading',{name:'Backdated VAT exposure · not tax collected',exact:true}).waitFor();
    expect(host.engine.db.prepare('SELECT tax_snapshot FROM sales WHERE id=?').get(sale.id)).toEqual(before);
    expect(consoleErrors).toEqual([]);
  });

});
