import { createRequire } from 'node:module';
import { existsSync } from 'node:fs';
import { join } from 'node:path';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { buildApp } from '../../apps/api/src/app';
import { sha256 } from '../../apps/api/src/security';
import { serveStatic } from '../../scripts/static';
import { ADMIN, startCloud, type Cloud } from '../cloud';
import { tempDir } from '../helpers';
const pw = (() => { try { return createRequire(import.meta.url)('playwright'); } catch { return null; } })();
const root = join(import.meta.dirname, '../..');
const built = existsSync(join(root, 'apps/admin-web/dist/index.html'));
describe.skipIf(!pw || !built)('administrator dashboard CRUD', () => {
  let cloud: Cloud, app: Awaited<ReturnType<typeof buildApp>>, web: Awaited<ReturnType<typeof serveStatic>>, browser: any, page: any;
  let clientId = '', deviceToken = '';
  let nativeDialogs = 0;
  const pageErrors: string[] = [];
  beforeAll(async () => {
    cloud = await startCloud();
    const other = await cloud.createClient('Unrelated business');
    const otherDevice = await cloud.api('POST', '/v1/devices/activate', { code: other.code, deviceName: 'Other synthetic laptop', appVersion: '1.0' }, null);
    expect(otherDevice.status).toBe(200);
    deviceToken = otherDevice.body.deviceToken;
    web = await serveStatic(join(root, 'apps/admin-web/dist'), 0, { '/config.js': `window.MANSORA_API_URL = ${JSON.stringify(cloud.url)};` });
    await cloud.app.close();
    app = await buildApp({ db: cloud.db, backupDir: tempDir(), adminOrigins: [web.url] });
    await app.listen({ port: Number(new URL(cloud.url).port), host: '127.0.0.1' });
    browser = await pw.chromium.launch();
    page = await browser.newPage({ viewport: { width: 1366, height: 768 } });
    page.setDefaultTimeout(10_000);
    page.on('pageerror', (error: Error) => pageErrors.push(error.message));
    page.on('dialog', async (dialog: any) => { nativeDialogs++; await dialog.dismiss(); });
    await page.goto(web.url);
  });
  afterAll(async () => {
    await browser?.close();
    if (web) await new Promise<void>((resolve) => web.server.close(() => resolve()));
    await app?.close(); await cloud?.close();
  });
  const nav = (name: string) => page.getByRole('navigation').getByRole('button', { name, exact: true }).click();
  async function login() {
    await page.getByLabel('Email', { exact: true }).fill(ADMIN.email);
    await page.getByLabel('Password', { exact: true }).fill(ADMIN.password);
    await page.getByRole('button', { name: 'Sign in', exact: true }).click();
    await page.getByRole('button', { name: 'Sign out', exact: true }).waitFor();
  }
  it('creates/edits a plan and client, changes status, filters clients and ticks/unticks onboarding', async () => {
    await login();
    await nav('Service plans');
    await page.getByRole('button', { name: 'Add plan', exact: true }).click();
    await page.getByLabel('Plan name').fill('Browser plan');
    await page.getByLabel('Billing amount (GHS)').fill('125.50');
    await page.getByLabel('Included support services').fill('Synthetic support');
    await page.getByRole('dialog').getByRole('button', { name: 'Save', exact: true }).click();
    await page.getByRole('row').filter({ hasText: 'Browser plan' }).click();
    await page.getByLabel('Plan name').fill('Updated browser plan');
    await page.getByLabel('Billing amount (GHS)').fill('150.25');
    await page.getByRole('dialog').getByRole('button', { name: 'Save', exact: true }).click();
    await page.getByRole('cell', { name: 'Updated browser plan', exact: true }).waitFor();
    const plans = (await cloud.api('GET', '/v1/admin/plans')).body;
    expect(plans.find((p: any) => p.name === 'Updated browser plan').price).toBe(15025);
    await nav('Clients');
    await page.getByRole('button', { name: 'Add client', exact: true }).click();
    await page.getByLabel('Business name').fill('Browser business');
    await page.getByLabel('Primary owner').fill('Synthetic owner');
    await page.getByRole('button', { name: 'Create client', exact: true }).click();
    await page.getByRole('heading', { name: 'Browser business', exact: true }).waitFor();
    clientId = (await cloud.api('GET', '/v1/admin/clients')).body.find((c: any) => c.name === 'Browser business').id;
    await page.getByRole('button', { name: 'Edit', exact: true }).click();
    await page.getByLabel('Business name').fill('Updated browser business');
    await page.getByLabel('Account status').selectOption('suspended');
    await page.getByRole('dialog').getByRole('button', { name: 'Save', exact: true }).click();
    await page.getByRole('heading', { name: 'Updated browser business', exact: true }).waitFor();
    const step = page.getByRole('checkbox').nth(1);
    await step.check(); await expect.poll(() => step.isChecked()).toBe(true);
    await expect.poll(async () => (await cloud.api('GET', `/v1/admin/clients/${clientId}`)).body.onboarding[1].completed_at != null).toBe(true);
    await step.uncheck();
    await expect.poll(async () => (await cloud.api('GET', `/v1/admin/clients/${clientId}`)).body.onboarding[1].completed_at).toBeNull();
    const onboardingUrl = `${cloud.url}/v1/admin/clients/${clientId}/onboarding/*`;
    await page.route(onboardingUrl, (route: any) => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ code: 'TEST_UNAVAILABLE', message: 'Synthetic onboarding save failure' }) }));
    await step.click();
    await page.getByRole('alert').getByText('Synthetic onboarding save failure', { exact: true }).waitFor();
    await expect.poll(() => step.isChecked()).toBe(false);
    expect((await cloud.api('GET', `/v1/admin/clients/${clientId}`)).body.onboarding[1].completed_at).toBeNull();
    await page.unroute(onboardingUrl);
    await nav('Clients');
    await page.getByLabel('Search clients').fill('synthetic OWNER');
    await page.getByRole('cell', { name: /Updated browser business/ }).waitFor();
    expect(await page.getByRole('cell', { name: /Unrelated business/ }).count()).toBe(0);
    await page.getByLabel('Client status filter').selectOption('active');
    await page.getByText('No clients match these filters', { exact: true }).waitFor();
    await page.getByLabel('Client status filter').selectOption('suspended');
    await page.getByRole('row').filter({ hasText: 'Updated browser business' }).click();
  });
  it('assigns a subscription, creates activation, confirms deactivation and scopes the client audit', async () => {
    await page.getByRole('button', { name: 'Change', exact: true }).click();
    const dialog = page.getByRole('dialog', { name: 'Service plan', exact: true });
    await dialog.getByLabel(/^Plan/).selectOption({ label: 'Updated browser plan · GHS 150.25 monthly' });
    await dialog.getByLabel(/^Status/).selectOption('active');
    await dialog.getByLabel('Renewal date').fill('2027-01-01');
    await dialog.getByRole('button', { name: 'Save', exact: true }).click();
    await expect.poll(async () => (await cloud.api('GET', `/v1/admin/clients/${clientId}`)).body.client.subscription_status).toBe('active');
    await page.getByRole('button', { name: 'Create activation code', exact: true }).click();
    const code = await page.getByTestId('activation-code').innerText();
    expect(code).toMatch(/^MNS-/);
    await page.getByRole('dialog').getByRole('button', { name: 'Done', exact: true }).click();
    const activation = await cloud.api('POST', '/v1/devices/activate', { code, deviceName: 'Synthetic laptop', appVersion: '1.0' }, null);
    expect(activation.status).toBe(200);
    await page.reload();
    await nav('Clients');
    await page.getByRole('row').filter({ hasText: 'Updated browser business' }).click();
    await page.getByRole('button', { name: 'Deactivate laptop', exact: true }).click();
    await page.getByRole('dialog', { name: 'Deactivate laptop', exact: true }).getByRole('button', { name: 'Cancel', exact: true }).click();
    expect((await cloud.api('GET', `/v1/admin/clients/${clientId}`)).body.devices.find((d: any) => d.id === activation.body.deviceId).status).toBe('active');
    await page.getByRole('button', { name: 'Deactivate laptop', exact: true }).click();
    await page.getByRole('dialog', { name: 'Deactivate laptop', exact: true }).getByRole('button', { name: 'Deactivate laptop', exact: true }).click();
    await expect.poll(async () => (await cloud.api('GET', `/v1/admin/clients/${clientId}`)).body.devices.find((d: any) => d.id === activation.body.deviceId).status).toBe('revoked');
    expect(nativeDialogs).toBe(0);
    await page.getByRole('tab', { name: 'Client audit', exact: true }).click();
    await page.getByRole('cell', { name: 'device.revoked', exact: true }).waitFor();
    await page.getByRole('cell', { name: 'subscription.updated', exact: true }).waitFor();
    expect(await page.getByRole('cell', { name: 'Unrelated business', exact: true }).count()).toBe(0);
    const audits = (await cloud.api('GET', `/v1/admin/audit?tenantId=${clientId}`)).body;
    expect(audits.length).toBeGreaterThan(3);
    expect(audits.every((row: any) => row.tenant_name === 'Updated browser business')).toBe(true);
  });
  it('returns expired sessions and non-admin tokens to sign in', async () => {
    const token = await page.evaluate(() => sessionStorage.getItem('mansora-admin-token'));
    await cloud.db.platform((q) => q("UPDATE admin_sessions SET expires_at = now() - interval '1 second' WHERE token_hash = $1", [sha256(token)]));
    await nav('Overview');
    await page.getByRole('heading', { name: 'Administrator sign in', exact: true }).waitFor();
    expect(await page.evaluate(() => sessionStorage.getItem('mansora-admin-token'))).toBeNull();
    expect((await cloud.api('GET', '/v1/sync/pull', undefined, deviceToken)).status).toBe(200);
    expect((await cloud.api('GET', '/v1/admin/clients', undefined, deviceToken)).status).toBe(401);
    await page.evaluate((value: string) => sessionStorage.setItem('mansora-admin-token', value), deviceToken);
    await page.reload();
    await page.getByRole('heading', { name: 'Administrator sign in', exact: true }).waitFor();
    expect(await page.evaluate(() => sessionStorage.getItem('mansora-admin-token'))).toBeNull();
    expect(pageErrors).toEqual([]);
  });
});
