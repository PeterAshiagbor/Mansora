import { PGlite } from '@electric-sql/pglite';
import { afterAll, beforeAll, expect, it } from 'vitest';
import { capturePostgres, restorePostgres, type RecoveryQuery } from '../../scripts/recovery/postgres';
import { packSnapshot, unpackSnapshot, type SystemSnapshot } from '../../scripts/recovery/archive';
let source: PGlite, target: PGlite, snapshot: SystemSnapshot;
const ddl = `CREATE TABLE schema_migrations (id integer PRIMARY KEY, name text NOT NULL); INSERT INTO schema_migrations VALUES (1,'synthetic-test-schema');
 CREATE TABLE tenants (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text NOT NULL);
 CREATE TABLE sales (id bigint PRIMARY KEY, tenant_id bigint NOT NULL REFERENCES tenants(id), amount numeric(30,0) NOT NULL);`;
const query = (db: any): RecoveryQuery => async (sql, params) => (await db.query(sql, params)).rows;
beforeAll(async () => {
  source = await PGlite.create(); target = await PGlite.create(); await source.exec(ddl); await target.exec(ddl);
  await source.exec("INSERT INTO tenants VALUES (42, 'Synthetic shop'); INSERT INTO sales VALUES (1,42,9007199254740993)");
  const captured = await source.transaction(t => capturePostgres(query(t)));
  snapshot = unpackSnapshot(packSnapshot({ version: 1, createdAt: new Date().toISOString(), ...captured, files: [] }, 'b'.repeat(64)), 'b'.repeat(64));
});
afterAll(async () => { await source?.close(); await target?.close(); });
it('restores dependency order and exact numeric JSON through an authenticated envelope, with constraints and identities intact', async () => {
  expect(snapshot.tables.map(table => table.name)).toEqual(['sales', 'tenants']);
  expect(await target.transaction(t => restorePostgres(query(t), snapshot))).toEqual({ tables: 2, rows: 2 });
  expect((await target.query<{ amount: string }>('SELECT amount::text AS amount FROM sales')).rows[0].amount).toBe('9007199254740993');
  expect((await target.query<{ id: number }>("INSERT INTO tenants(name) VALUES ('Next synthetic tenant') RETURNING id::integer AS id")).rows[0].id).toBe(43);
  await expect(target.query('INSERT INTO sales VALUES (2,999,1)')).rejects.toThrow();
});
it('refuses occupied or incompatible destinations without replacing data', async () => {
  await expect(target.transaction(t => restorePostgres(query(t), snapshot))).rejects.toThrow(/empty/);
  expect((await target.query('SELECT count(*)::text AS count FROM sales')).rows[0]).toEqual({ count: '1' });
  const incompatible = await PGlite.create(); try { await incompatible.exec(ddl + 'ALTER TABLE tenants ADD COLUMN extra text;'); await expect(incompatible.transaction(t => restorePostgres(query(t), snapshot))).rejects.toThrow(/schema/); } finally { await incompatible.close(); }
});
it('restores the subscription/mandate reference cycle and restores immediate foreign-key enforcement before commit', async () => {
  const a = await PGlite.create(), b = await PGlite.create();
  const cycle = `CREATE TABLE schema_migrations (id integer PRIMARY KEY, name text NOT NULL); INSERT INTO schema_migrations VALUES (1,'cycle-fixture');
    CREATE TABLE subscriptions (id integer PRIMARY KEY, mandate_id integer);
    CREATE TABLE mandates (id integer PRIMARY KEY, subscription_id integer NOT NULL REFERENCES subscriptions(id));
    ALTER TABLE subscriptions ADD CONSTRAINT subscriptions_mandate_fk FOREIGN KEY (mandate_id) REFERENCES mandates(id);`;
  try {
    await a.exec(cycle); await b.exec(cycle); await a.exec('INSERT INTO subscriptions VALUES (1,NULL); INSERT INTO mandates VALUES (2,1); UPDATE subscriptions SET mandate_id=2 WHERE id=1;');
    const captured = await a.transaction(t => capturePostgres(query(t))), archive: SystemSnapshot = { version: 1, createdAt: new Date().toISOString(), ...captured, files: [] };
    expect(await b.transaction(t => restorePostgres(query(t), archive))).toEqual({ tables: 2, rows: 2 });
    expect((await b.query('SELECT * FROM subscriptions')).rows).toEqual([{ id: 1, mandate_id: 2 }]);
    expect((await b.query("SELECT count(*)::text AS n FROM pg_constraint WHERE contype='f' AND condeferrable")).rows[0]).toEqual({ n: '0' });
    await expect(b.query('INSERT INTO mandates VALUES (3,999)')).rejects.toThrow();
  } finally { await a.close(); await b.close(); }
});
